export type Phrase = keyof typeof zh;

/** The language: the one chosen on this browser, else the browser's own. */
export type Language = "zh" | "en" | "ja";

export function chosenLanguage(): Language | undefined {
  try {
    const stored = localStorage.getItem("nlteam.language");
    return stored === "zh" || stored === "en" || stored === "ja" ? stored : undefined;
  } catch {
    return undefined;
  }
}

function browserLanguage(): Language {
  const spoken = navigator.language.toLowerCase();
  return spoken.startsWith("zh") ? "zh" : spoken.startsWith("ja") ? "ja" : "en";
}

export const language: Language = chosenLanguage() ?? browserLanguage();

/** Choose a language for this browser; the page reloads to speak it. */
export function chooseLanguage(next: Language | undefined): void {
  try {
    if (next === undefined) localStorage.removeItem("nlteam.language");
    else localStorage.setItem("nlteam.language", next);
  } catch {
    /* nothing to remember with */
  }
  window.location.reload();
}

const table = { zh, en, ja }[language];
document.documentElement.lang = { zh: "zh-CN", en: "en", ja: "ja" }[language];

export function t(phrase: Phrase, values: Record<string, string> = {}): string {
  return table[phrase].replace(/\{(\w+)\}/g, (_, name: string) => values[name] ?? "");
}
